// Clipboard history widget: remembers the last 8 copied texts (in memory
// only, never saved). Shows the newest for 20 s after each copy; clicking
// opens its drawer to copy an older one again. Skips anything a password manager marks as concealed or
// transient, and anything that looks like a password, token or key. Shown once something was copied.
import AppKit
import SwiftUI

@MainActor
final class Clipboard: ObservableObject {
    struct Entry: Identifiable, Equatable {
        let id = UUID()
        let text: String
        let date: Date
    }

    @Published private(set) var entries: [Entry] = []
    /// True for a short while after each copy; the widget only shows then.
    @Published private(set) var recent = false
    private static let showFor: TimeInterval = 20

    private var changeCount = NSPasteboard.general.changeCount
    private static let skipped: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                               "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    init() {
        if Config.demo != nil {
            entries = ["brew install ffmpeg", "https://example.com/docs", "Meet at 7?"]
                .enumerated().map { Entry(text: $0.element, date: Date().addingTimeInterval(Double(-$0.offset * 400))) }
            recent = true
            return
        }
        Timer.scheduledTimer(withTimeInterval: 1, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
    }

    private func check() {
        let board = NSPasteboard.general
        guard board.changeCount != changeCount else { return }
        changeCount = board.changeCount
        let types = Set((board.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipped),
              let text = board.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
              !text.isEmpty, !Self.looksSecret(text)
        else { return }
        entries.removeAll { $0.text == text }
        let entry = Entry(text: text, date: Date())
        entries.insert(entry, at: 0)
        if entries.count > 8 { entries.removeLast() }
        recent = true
        DispatchQueue.main.asyncAfter(deadline: .now() + Self.showFor) {
            // Stay while its drawer is open; go once the newest copy is old.
            if self.entries.first?.id == entry.id, Drawers.shared.open != "clipboard" { self.recent = false }
        }
    }

    /// Things that look like passwords, tokens or keys are never kept, even
    /// when the app they came from didn't mark them as private: a single
    /// long word mixing letters and digits, UUIDs (WaniKani tokens look like
    /// that), and known key formats.
    static func looksSecret(_ text: String) -> Bool {
        guard !text.contains(where: \.isWhitespace) else { return false }
        let prefixes = ["sk-", "sk_", "pk_", "rk_", "ghp_", "gho_", "ghs_", "github_pat_", "glpat-", "xox", "AKIA", "eyJ", "AIza", "ya29."]
        if prefixes.contains(where: text.hasPrefix) { return true }
        if text.range(of: #"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$"#, options: .regularExpression) != nil { return true }
        // A URL or path is fine; a long random-looking word is not.
        if text.contains("://") || text.hasPrefix("/") || text.hasPrefix("~") { return false }
        let letters = text.contains(where: \.isLetter), digits = text.contains(where: \.isNumber)
        let mixedCase = text.contains(where: \.isUppercase) && text.contains(where: \.isLowercase)
        return text.count >= 16 && letters && digits && (mixedCase || text.count >= 24)
            || (text.count >= 8 && text.count < 64 && letters && digits && text.contains(where: { "!@#$%^&*".contains($0) }))
    }

    func copy(_ entry: Entry) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(entry.text, forType: .string)
        Drawers.shared.open = nil
    }
}

struct ClipboardView: View {
    @ObservedObject var clipboard: Clipboard

    var body: some View {
        if let latest = clipboard.entries.first {
            Button { Drawers.shared.toggle("clipboard") } label: {
                HStack(spacing: 10) {
                    Tile { Image(systemName: "doc.on.clipboard").font(.system(size: 17, weight: .medium)) }
                    Lines(title: latest.text.replacingOccurrences(of: "\n", with: " "),
                          subtitle: clipboard.entries.count > 1 ? "Copied · \(clipboard.entries.count - 1) more" : "Copied \(ago(latest.date))",
                          maxWidth: 140)
                        .id(latest.id)
                        .transition(.blurReplace)
                }
                .contentShape(Rectangle())
            }
            .buttonStyle(WidgetPress())
            .animation(.spring(duration: 0.4, bounce: 0.15), value: latest.id)
        }
    }
}

/// Drawer content: recent copies; click one to copy it again.
struct ClipboardList: View {
    @ObservedObject var clipboard: Clipboard

    var body: some View {
        VStack(alignment: .leading, spacing: 2) {
            ForEach(clipboard.entries) { entry in
                Button { clipboard.copy(entry) } label: {
                    HStack {
                        Text(entry.text.replacingOccurrences(of: "\n", with: " ")).lineLimit(1)
                        Spacer()
                        Text(ago(entry.date)).font(.system(size: 11)).foregroundStyle(.secondary)
                    }
                    .font(.system(size: 13, weight: .medium))
                    .padding(.horizontal, 10).padding(.vertical, 7)
                    .contentShape(Rectangle())
                }
                .buttonStyle(HoverRow())
            }
        }
        .padding(8)
        .frame(width: 300)
        .card()
    }
}

/// List row that highlights on hover.
struct HoverRow: ButtonStyle {
    func makeBody(configuration: Configuration) -> some View {
        Highlight(configuration: configuration)
    }

    private struct Highlight: View {
        let configuration: Configuration
        @State private var hovering = false

        var body: some View {
            configuration.label
                .background(RoundedRectangle(cornerRadius: 8).fill(.white.opacity(configuration.isPressed ? 0.18 : hovering ? 0.1 : 0)))
                .onHover { hovering = $0 }
        }
    }
}
